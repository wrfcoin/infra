#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
LEDGER="${ROUTE_LEDGER:-${ROOT}/testnet/edge/route-ledger.yml}"
CADDY="${CADDY_FILE:-${ROOT}/testnet/edge/public_onboarding.caddy}"
OUTPUT="${OUTPUT_FILE:-${ROOT}/testnet/PUBLIC_ENDPOINTS.md}"
MODE="${1:-}"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

python3 - "$LEDGER" "$CADDY" >"$tmp" <<'PY'
import re
import sys
from pathlib import Path

ledger_path, caddy_path = map(Path, sys.argv[1:])
services = {}
current = None
for raw in ledger_path.read_text().splitlines():
    match = re.match(
        r"^  ([A-Za-z0-9_-]+):(?:\s*\{(.*?)\})?(?:\s*#.*)?\s*$", raw
    )
    if match:
        current = match.group(1)
        services[current] = {}
        inline = (match.group(2) or "").strip()
        for key in ("exposure", "path", "upstream", "auth"):
            value = re.search(rf"(?:^|,\s*){key}:\s*([^,}}]+)", inline)
            if value:
                services[current][key] = value.group(1).strip().strip('"')
        continue
    if current is None:
        continue
    value = re.match(r"^    (exposure|path|upstream|auth):\s*(.+?)\s*$", raw)
    if value:
        services[current][value.group(1)] = value.group(2).split("#", 1)[0].strip().strip('"')
    ports = re.match(r"^    ports:\s*\{(.+?)\}(?:\s*#.*)?\s*$", raw)
    if ports:
        services[current]["ports"] = {
            key: binding
            for key, binding in re.findall(r'(\w+):\s*"([^"]+)"', ports.group(1))
        }
lines = caddy_path.read_text().splitlines()

inside = False
depth = 0
matchers = []
current = None
for line in lines:
    stripped = line.strip()
    if not inside and stripped == "(public_onboarding_api) {":
        inside = True
        depth = 1
        continue
    if not inside:
        continue
    if stripped.startswith("@") and stripped.endswith("{"):
        current = {"name": stripped.split()[0][1:], "method": [], "paths": [], "gate": None, "query": None, "bearer": False}
    elif current and stripped.startswith("method "):
        current["method"] = stripped.split()[1:]
    elif current and stripped.startswith("path "):
        current["paths"] += stripped.split()[1:]
    elif current and stripped.startswith("path_regexp "):
        current["paths"].append("regex: " + stripped.removeprefix("path_regexp "))
    elif current and stripped.startswith("vars "):
        # infra#983: an env-gated matcher, e.g. `vars {env.PUBLIC_READONLY_API} on`.
        gate = re.fullmatch(r"vars \{env\.([A-Z0-9_]+)\} (\S+)", stripped)
        if gate is None:
            raise SystemExit(f"unrecognised vars matcher in the allowlist: {stripped}")
        current["gate"] = gate.groups()
    elif current and stripped == 'header Authorization "Bearer *"':
        # S1: the own-wallet reads are proxied only when a Bearer credential is present.
        current["bearer"] = True
    elif current and stripped.startswith("expression "):
        # stage15 readiness: a query lock, e.g.
        # expression `{query} == "" || {query} == "limit=1"`. Only exact
        # {query} equalities joined by || are understood; anything else is
        # refused rather than rendered as something it is not.
        body = re.fullmatch(r"expression `(.*)`", stripped)
        # backend#1456: the leaderboard's exact-grammar query lock, `{query}.matches('<anchored regex>')`.
        regex = re.fullmatch(r"\{query\}\.matches\('(\^[^'`]*\$)'\)", body.group(1)) if body else None
        if regex:
            current["query"] = ["regex:" + regex.group(1)]
            continue
        terms = body.group(1).split(" || ") if body else []
        values = []
        for term in terms:
            eq = re.fullmatch(r'\{query\} == "([^"`]*)"', term)
            rx = re.fullmatch(r"\{query\}\.matches\('(\^[^'`]*\$)'\)", term)
            values.append(eq.group(1) if eq else ("regex:" + rx.group(1) if rx else None))
        if not terms or any(value is None for value in values):
            raise SystemExit(f"unrecognised expression matcher in the allowlist: {stripped}")
        current["query"] = values
    if current and stripped == "}":
        if current["method"] and current["paths"]:
            matchers.append(current)
        current = None
    depth += line.count("{") - line.count("}")
    if depth == 0:
        break

print("# WRFCoin testnet public endpoints\n")
print("> Generated by `testnet/scripts/render-public-endpoints.sh`; do not edit by hand.\n")
print("The public origin is `${WRFCOIN_FUNNEL_ORIGIN}`. This document describes configuration in source; it does not claim that an edge is currently deployed or healthy. Runtime state, when an owner deploys this change, is available at `GET /status.json`.\n")
print("The node's checked first-tranche route contract is supplied by core4 draft PR #3262 (`docs/api/launch-api.openapi.yaml`). The node remains tailnet-direct and is not exposed by the public edge.\n")
print("## Public edge exact allowlist\n")
print("| Method | Path | Auth |")
print("|---|---|---|")
for matcher in matchers:
    for method in matcher["method"]:
        for path in matcher["paths"]:
            auth = "none/read-only" if method == "GET" else "route-specific"
            # weather-routes.js authenticates this GET and selects req.user.address.
            if matcher["name"] == "station_mobile_status":
                auth = "wallet JWT (own station only); read-only"
            # infra#1095: backend station-owner-routes.ts authenticates per tx kind.
            if matcher["name"] == "station_owner_actions":
                auth = (
                    "route-specific (station alias path only; wallet JWT equal to a signer for transfer, owner action "
                    "and recovery cancel, signature-only for recovery execute; the signed tx is forwarded unaltered; "
                    "body at most 8 KiB; own rate zone 10 per 10 min per IP)"
                )
            # Self-serve bond grant (spec 2026-10-23 section 2): the edge's own limits on the backend proxy.
            if matcher["name"] == "faucet_bond_grant":
                auth = "route-specific (body at most 8 KiB at the edge; shared faucet rate zone 5 per minute per IP)"
            # S1: backend wallet-routes.js requireAuth + requireOwnAddress.
            if matcher["bearer"]:
                auth = (
                    "wallet JWT (own address only); read-only; the edge proxies it only when the request carries "
                    "an `Authorization: Bearer` header"
                )
            # backend#389 payout notifications: wallet-login writes, no email or user URL, own rate zone.
            if matcher["name"].startswith("public_notifications_") and matcher["name"] != "public_notifications_config":
                auth = (
                    "wallet JWT (own address only; the edge proxies it only with an `Authorization: Bearer` header); "
                    "notification subscription for a browser push endpoint or an ntfy topic, never an email or URL; "
                    "rate zone notify_write 10 per minute per IP"
                    if matcher["bearer"] else
                    "none (possession of the push endpoint or ntfy topic removes it); body at most 4 KiB; "
                    "rate zone notify_write 10 per minute per IP"
                )
            # Passkey-wallet payout notifications: no JWT; the body's WebAuthn assertion is the authorization.
            if matcher["name"].startswith("public_notifications_passkey_"):
                auth = (
                    "none at the edge (no Bearer; passkey wallet: the backend checks a WebAuthn assertion over a "
                    "single-use nonce, address derived from the P-256 key); "
                    + ("issues that nonce; body at most 1 KiB; " if matcher["name"].endswith("_challenge") else "body at most 4 KiB; ")
                    + "notification subscription for a browser push endpoint or an ntfy topic, never an email or URL; "
                    "rate zone notify_write 10 per minute per IP"
                )
            if matcher["gate"]:
                name, value = matcher["gate"]
                auth += f"; **OFF unless the edge env has `{name}={value}`** (compose default off)"
            if matcher["query"] is not None:
                if len(matcher["query"]) > 1 and any(v.startswith("regex:") for v in matcher["query"]):
                    parts = [
                        "none" if v == "" else (
                            "match `" + v.removeprefix("regex:").replace("|", "\\|") + "`"
                            if v.startswith("regex:") else f"`{v}`"
                        )
                        for v in matcher["query"]
                    ]
                    auth += "; query string must be exactly " + " or ".join(parts) + " (anything else 404s)"
                elif matcher["query"][0].startswith("regex:"):
                    pattern = matcher["query"][0].removeprefix("regex:").replace("|", "\\|")
                    auth += f"; query string must match `{pattern}` exactly (anything else 404s)"
                else:
                    allowed = ["none" if value == "" else f"`{value}`" for value in matcher["query"]]
                    auth += "; query string must be exactly " + " or ".join(allowed) + " (anything else 404s)"
            cell = path.replace("|", "\\|")  # GFM: a bare | splits the cell, even in code
            print(f"| `{method}` | `{cell}` | {auth} |")

print("\n## Tailnet only\n")
print("| Service | Endpoint | Auth |")
print("|---|---|---|")
for name, cfg in services.items():
    if not isinstance(cfg, dict):
        continue
    exposure = cfg.get("exposure")
    if exposure == "tailnet-direct":
        ports = cfg.get("ports", {})
        rendered = []
        for label, binding in ports.items():
            port = str(binding).rsplit(":", 1)[-1]
            rendered.append(f"{label}: http://<CT101 tailnet IPv4>:{port}")
        endpoint = "; ".join(rendered) or "tailnet direct (see compose)"
    elif exposure == "tailnet-gateway":
        endpoint = f"<tailnet gateway origin>{cfg.get('path', '/')}"
    else:
        continue
    print(f"| `{name}` | `{endpoint}` | {cfg.get('auth', 'service-specific')} |")

print("\n## Loopback only / not exposed\n")
print("| Service | Exposure decision |")
print("|---|---|")
for name, cfg in services.items():
    if isinstance(cfg, dict) and cfg.get("exposure") in {"decided-by-599", "never"}:
        print(f"| `{name}` | `{cfg['exposure']}` |")
PY

if [[ "$MODE" == "--check" ]]; then
  if ! cmp -s "$tmp" "$OUTPUT"; then
    diff -u "$OUTPUT" "$tmp" || true
    echo "ERROR: ${OUTPUT} is stale; regenerate it" >&2
    exit 1
  fi
elif [[ -n "$MODE" ]]; then
  echo "usage: $0 [--check]" >&2
  exit 2
else
  cp "$tmp" "$OUTPUT"
fi
