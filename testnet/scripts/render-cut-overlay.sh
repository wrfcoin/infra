#!/usr/bin/env bash
# Default cut overlay requires only wrfcoin-node. A seed block is emitted only
# with the public pin WRFCOIN_CUT_INCLUDE_SEED=1; then the base must define seed.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PINS="${ROOT}/cut-pins.env"
OUT="${ROOT}/docker-compose.cut.yml"
CHECK=0

usage() {
  echo 'usage: render-cut-overlay.sh [--pins FILE] [--out FILE] [--check]'
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --pins) PINS="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    --check) CHECK=1; shift ;;
    --help|-h) usage; exit 0 ;;
    *) echo "CUT_OVERLAY=FAIL unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

[[ -r "$PINS" ]] || { echo "CUT_OVERLAY=FAIL pins file missing: $PINS" >&2; exit 1; }
for file in "$PINS" "$OUT" "$OUT.custody.json"; do
  if [[ -L "$file" || ( -e "$file" && ! -f "$file" ) ]]; then
    echo 'CUT_OVERLAY=FAIL custody paths must be regular files without symlinks' >&2
    exit 1
  fi
done
GENESIS_HASH="$(awk -F= '/^WRFCOIN_CUT_GENESIS_HASH=/ {print substr($0, index($0, "=") + 1); exit}' "$PINS")"
[[ "$GENESIS_HASH" =~ ^[0-9a-f]{64}$ ]] || {
  echo 'CUT_OVERLAY=FAIL WRFCOIN_CUT_GENESIS_HASH must be 64 lowercase hex' >&2
  exit 1
}

# core4#3361 option B: the genesis faucet address is a cut input that only the
# node cutting block 1 reads, and it goes onto wrfcoin-node as a literal next to
# the genesis hash. An EMPTY pin means "this chain has none" (the live chain 777
# predates #3361), and the overlay then carries no faucet line at all. A
# non-empty pin must be 0x + 40 hex and not the zero address. The value is
# never printed.
FAUCET="$(awk -F= '/^WRFCOIN_CUT_GENESIS_FAUCET_ADDRESS=/ {print substr($0, index($0, "=") + 1); exit}' "$PINS")"
FAUCET="${FAUCET%\"}"; FAUCET="${FAUCET#\"}"; FAUCET="${FAUCET%\'}"; FAUCET="${FAUCET#\'}"
FAUCET="$(printf '%s' "$FAUCET" | tr -d '[:space:]' | tr 'A-F' 'a-f')"
if [[ -n "$FAUCET" ]]; then
  [[ "$FAUCET" =~ ^0x[0-9a-f]{40}$ && "$FAUCET" != "0x0000000000000000000000000000000000000000" ]] || {
    echo 'CUT_OVERLAY=FAIL WRFCOIN_CUT_GENESIS_FAUCET_ADDRESS must be 0x + 40 hex and not the zero address' >&2
    exit 1
  }
fi

# Public native snapshot-ingest trust; keep distinct from the future join-archive key.
# Existing owner-approved cut pin wins over shell/.env; absent/empty is explicitly no trust.
TRUST_COUNT="$(awk '/^WRFCOIN_CUT_SNAPSHOT_TRUSTED_SIGNERS=/{n++} END{print n+0}' "$PINS")"
[[ "$TRUST_COUNT" -le 1 ]] || { echo 'CUT_OVERLAY=FAIL duplicate snapshot trust pin' >&2; exit 1; }
TRUST="$(awk -F= '/^WRFCOIN_CUT_SNAPSHOT_TRUSTED_SIGNERS=/{print substr($0,index($0,"=")+1)}' "$PINS")"
TRUST="${TRUST%\"}"; TRUST="${TRUST#\"}"; TRUST="${TRUST%\'}"; TRUST="${TRUST#\'}"
TRUST="$(printf '%s' "$TRUST" | tr 'A-F' 'a-f')"
if [[ -n "$TRUST" && ! "$TRUST" =~ ^[0-9a-f]{64}(,[0-9a-f]{64})*$ ]]; then
  echo 'CUT_OVERLAY=FAIL snapshot trust pin requires comma-separated64hex public keys' >&2
  exit 1
fi
SEED_COUNT="$(awk '/^WRFCOIN_CUT_INCLUDE_SEED=/{n++} END{print n+0}' "$PINS")"
[[ "$SEED_COUNT" -le 1 ]] || { echo 'CUT_OVERLAY=FAIL duplicate seed inclusion pin' >&2; exit 1; }
SEED="$(awk -F= '/^WRFCOIN_CUT_INCLUDE_SEED=/{print substr($0,index($0,"=")+1)}' "$PINS")"
[[ -z "$SEED" || "$SEED" == 0 || "$SEED" == 1 ]] || {
  echo 'CUT_OVERLAY=FAIL seed inclusion pin requires 0 or 1' >&2; exit 1;
}

if [[ "$SEED" == 1 && -z "$TRUST" ]]; then
  echo 'CUT_OVERLAY=FAIL seed inclusion requires a nonempty snapshot trust pin' >&2
  exit 1
fi

# One canonical byte sequence feeds both publication and verification. Check
# uses a disposable file only; it never repairs a missing/stale custody pair.
if [[ $CHECK -eq 1 ]]; then
  TMP="$(mktemp)"
else
  mkdir -p "$(dirname "$OUT")"
  TMP="$(mktemp "$(dirname "$OUT")/.docker-compose.cut.XXXXXX")"
fi
trap 'rm -f "$TMP"' EXIT
printf '%s\n' \
  '# Generated by testnet/scripts/render-cut-overlay.sh; do not hand-edit.' \
  'services:' \
  '  wrfcoin-node:' \
  '    environment:' \
  "      WRFCOIN_GENESIS_HASH: '$GENESIS_HASH'" > "$TMP"
if [[ -n "$FAUCET" ]]; then
  printf '%s\n' "      WRFCOIN_GENESIS_FAUCET_ADDRESS: '$FAUCET'" >> "$TMP"
fi
printf '%s\n' \
  '      # Unset/empty boots with an empty trust set; every snapshot ingest refuses.' \
  "      WRFCOIN_SNAPSHOT_TRUSTED_SIGNERS: '$TRUST'" >> "$TMP"
if [[ "$SEED" == 1 ]]; then
  printf '%s\n' \
    '  wrfcoin-seed:' \
    '    environment:' \
    '      # Unset/empty boots with an empty trust set; every snapshot ingest refuses.' \
    "      WRFCOIN_SNAPSHOT_TRUSTED_SIGNERS: '$TRUST'" >> "$TMP"
fi
CUSTODY="${ROOT}/../scripts/cut-overlay-custody.py"

if [[ $CHECK -eq 1 ]]; then
  [[ -r "$OUT" ]] || { echo "CUT_OVERLAY=FAIL overlay missing: $OUT" >&2; exit 1; }
  OBSERVED="$(awk '/WRFCOIN_GENESIS_HASH:/ {gsub(/['"'"'[:space:]]/, "", $2); print $2; exit}' "$OUT")"
  [[ "$OBSERVED" == "$GENESIS_HASH" ]] || {
    echo 'CUT_OVERLAY=FAIL overlay genesis does not match the pin' >&2
    exit 1
  }
  OBSERVED_FAUCET="$(awk '/WRFCOIN_GENESIS_FAUCET_ADDRESS:/ {gsub(/['"'"'"[:space:]]/, "", $2); print tolower($2); exit}' "$OUT")"
  [[ "$OBSERVED_FAUCET" == "$FAUCET" ]] || {
    echo "CUT_OVERLAY=FAIL overlay genesis faucet address does not match the pin (core4#3361)" >&2
    exit 1
  }
  python3 "$CUSTODY" --pins "$PINS" --overlay "$OUT" --expected "$TMP" --check
  echo "CUT_OVERLAY=PASS checked=$OUT genesis=$GENESIS_HASH faucet=$([[ -n "$FAUCET" ]] && echo pinned || echo none) custody=checked"
  exit 0
fi

mv "$TMP" "$OUT"
python3 "$CUSTODY" --pins "$PINS" --overlay "$OUT" --expected "$OUT"
trap - EXIT
echo "CUT_OVERLAY=PASS output=$OUT genesis=$GENESIS_HASH faucet=$([[ -n "$FAUCET" ]] && echo pinned || echo none) custody=recorded"
