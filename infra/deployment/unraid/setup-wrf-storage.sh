#!/bin/bash
# WRF Storage Node - Unraid Setup Script
# This script sets up a secure WRF storage node on Unraid

set -euo pipefail

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Configuration
WRF_DRIVE="/mnt/disks/wrf_storage"
WRF_CONFIG_DIR="/mnt/user/appdata/wrfcoin"
WRF_COMPOSE_FILE="$WRF_CONFIG_DIR/docker-compose.yml"

# Function to print colored messages
print_message() {
    local color=$1
    local message=$2
    echo -e "${color}[WRF Setup] ${message}${NC}"
}

print_success() { print_message "$GREEN" "$1"; }
print_warning() { print_message "$YELLOW" "$1"; }
print_error() { print_message "$RED" "$1"; }
print_info() { print_message "$BLUE" "$1"; }

# Check if running on Unraid
check_unraid() {
    print_info "Checking Unraid environment..."
    
    if [[ ! -f /etc/unraid-version ]]; then
        print_error "This script must be run on Unraid!"
        exit 1
    fi
    
    print_success "Unraid detected: $(cat /etc/unraid-version)"
}

# Check for required plugins
check_plugins() {
    print_info "Checking required Unraid plugins..."
    
    local required_plugins=(
        "unassigned.devices"
        "community.applications"
        "dynamix.docker.manager"
    )
    
    for plugin in "${required_plugins[@]}"; do
        if [[ ! -d "/var/log/plugins/$plugin" ]] && [[ ! -f "/boot/config/plugins/$plugin.plg" ]]; then
            print_warning "Plugin $plugin not found - please install from Community Applications"
        else
            print_success "Plugin $plugin is installed"
        fi
    done
}

# Setup dedicated storage drive
setup_storage_drive() {
    print_info "Setting up dedicated WRF storage drive..."
    
    # Check if WRF drive is mounted
    if [[ ! -d "$WRF_DRIVE" ]]; then
        print_error "WRF storage drive not found at $WRF_DRIVE"
        print_info "Please setup a dedicated drive using Unraid's 'Unassigned Devices' plugin:"
        print_info "1. Go to Main -> Unassigned Devices"
        print_info "2. Add a drive and format it as XFS"
        print_info "3. Mount it at $WRF_DRIVE"
        print_info "4. Re-run this script"
        exit 1
    fi
    
    # Create directory structure
    local dirs=("data" "logs" "config" "temp" "backups")
    for dir in "${dirs[@]}"; do
        local dir_path="$WRF_DRIVE/$dir"
        if [[ ! -d "$dir_path" ]]; then
            mkdir -p "$dir_path"
            print_success "Created directory: $dir_path"
        fi
    done
    
    # Set proper permissions
    chown -R 1001:1001 "$WRF_DRIVE"
    chmod -R 755 "$WRF_DRIVE"
    
    print_success "Storage drive setup complete"
}

# Create configuration directory
setup_config_directory() {
    print_info "Setting up configuration directory..."
    
    if [[ ! -d "$WRF_CONFIG_DIR" ]]; then
        mkdir -p "$WRF_CONFIG_DIR"
        print_success "Created config directory: $WRF_CONFIG_DIR"
    fi
    
    # Set permissions
    chown -R 99:100 "$WRF_CONFIG_DIR"  # nobody:users (Unraid default)
    chmod 755 "$WRF_CONFIG_DIR"
}

# Generate environment file
generate_env_file() {
    print_info "Generating environment configuration..."
    
    local env_file="$WRF_CONFIG_DIR/.env"
    
    if [[ -f "$env_file" ]]; then
        print_warning "Environment file already exists. Creating backup..."
        cp "$env_file" "$env_file.backup.$(date +%s)"
    fi
    
    cat > "$env_file" << 'EOF'
# WRF Storage Node Configuration
# Generated by setup script

# Wallet Configuration
# IMPORTANT: Replace with your actual WRF wallet address
WRF_WALLET_ADDRESS=wrf_your_wallet_address_here

# Storage Configuration
MAX_STORAGE_ALLOCATION=80%
MIN_FREE_SPACE=10GB
SHARD_SIZE=10MB
REDUNDANCY_FACTOR=3

# Network Configuration
AUTO_DISCOVERY=true
NETWORK_INTERFACE=eth0
ENABLE_UPNP=false

# Security Configuration
ENCRYPTION_REQUIRED=true
COMPRESSION_ENABLED=true
RATE_LIMIT_ENABLED=true
MAX_CONNECTIONS_PER_IP=10

# Monitoring Configuration
ENABLE_METRICS=true
LOG_LEVEL=info
HEALTH_CHECK_INTERVAL=30000

# Performance Tuning
NODE_OPTIONS=--max-old-space-size=2048
UV_THREADPOOL_SIZE=16

# Timezone (adjust as needed)
TZ=America/New_York
EOF
    
    print_success "Environment file created at: $env_file"
    print_warning "IMPORTANT: Edit $env_file and set your WRF wallet address!"
}

# Copy Docker Compose file
setup_docker_compose() {
    print_info "Setting up Docker Compose configuration..."
    
    # Copy the secure docker-compose file
    cp "docker-compose.secure.yml" "$WRF_COMPOSE_FILE"
    
    # Make it executable
    chmod 644 "$WRF_COMPOSE_FILE"
    
    print_success "Docker Compose file copied to: $WRF_COMPOSE_FILE"
}

# Create monitoring scripts
create_monitoring_scripts() {
    print_info "Creating monitoring and maintenance scripts..."
    
    # Health check script
    cat > "$WRF_CONFIG_DIR/health-check.sh" << 'EOF'
#!/bin/bash
# WRF Storage Node Health Check
# Add this to Unraid User Scripts plugin

CONTAINER="wrf-storage-node"
HEALTH_URL="http://localhost:7001/health"
LOG_FILE="/mnt/disks/wrf_storage/logs/health-check.log"

# Function to log with timestamp
log_message() {
    echo "$(date '+%Y-%m-%d %H:%M:%S') - $1" >> "$LOG_FILE"
}

# Check container status
if ! docker ps | grep -q "$CONTAINER"; then
    log_message "ERROR: WRF container not running"
    /usr/local/emhttp/webGui/scripts/notify -e "WRF Storage Alert" -s "Container Down" -d "WRF storage container is not running"
    exit 1
fi

# Check health endpoint
if ! curl -f -s "$HEALTH_URL" > /dev/null; then
    log_message "ERROR: WRF health check failed"
    /usr/local/emhttp/webGui/scripts/notify -e "WRF Storage Alert" -s "Health Check Failed" -d "WRF storage node health check failed"
    exit 1
fi

log_message "WRF storage node is healthy"
EOF

    # Log rotation script
    cat > "$WRF_CONFIG_DIR/log-rotation.sh" << 'EOF'
#!/bin/bash
# WRF Log Rotation Script
# Run daily via Unraid User Scripts

LOG_DIR="/mnt/disks/wrf_storage/logs"
MAX_SIZE="100M"
MAX_FILES=7

# Rotate logs if they exceed max size
find "$LOG_DIR" -name "*.log" -size +$MAX_SIZE -exec logrotate -f {} \;

# Clean old log files (keep last 7 days)
find "$LOG_DIR" -name "*.log.*" -mtime +$MAX_FILES -delete

echo "$(date '+%Y-%m-%d %H:%M:%S') - Log rotation completed"
EOF

    # Update script
    cat > "$WRF_CONFIG_DIR/update-wrf.sh" << 'EOF'
#!/bin/bash
# WRF Storage Node Update Script
# Run weekly via Unraid User Scripts

cd "/mnt/user/appdata/wrfcoin"

# Pull latest images
docker-compose pull

# Restart with new images
docker-compose up -d

# Clean up old images
docker image prune -f

echo "$(date '+%Y-%m-%d %H:%M:%S') - WRF storage node updated"
EOF

    # Make scripts executable
    chmod +x "$WRF_CONFIG_DIR"/*.sh
    
    print_success "Monitoring scripts created in: $WRF_CONFIG_DIR"
}

# Create firewall configuration helper
create_firewall_config() {
    print_info "Creating firewall configuration guide..."
    
    cat > "$WRF_CONFIG_DIR/firewall-rules.txt" << 'EOF'
WRF Storage Node - Firewall Configuration

=== pfSense/OPNsense Rules ===

1. Create WRF_VLAN interface (e.g., VLAN 100)
2. Add firewall rules for WRF_VLAN:

ALLOW Rules:
- Source: WRF_VLAN net, Destination: Any, Ports: 7001,7002, Protocol: TCP
- Source: WRF_VLAN net, Destination: DNS Servers, Port: 53, Protocol: UDP
- Source: WRF_VLAN net, Destination: NTP Servers, Port: 123, Protocol: UDP

BLOCK Rules:
- Source: WRF_VLAN net, Destination: LAN net, Protocol: Any
- Source: WRF_VLAN net, Destination: 192.168.0.0/16, Protocol: Any
- Source: WRF_VLAN net, Destination: 10.0.0.0/8, Protocol: Any
- Source: WRF_VLAN net, Destination: 172.16.0.0/12, Protocol: Any

ALLOW (last rule):
- Source: WRF_VLAN net, Destination: Any, Protocol: Any (Internet access)

=== Unraid Firewall (if using) ===
iptables -A INPUT -p tcp --dport 7001:7002 -j ACCEPT
iptables -A INPUT -p tcp --dport 7001:7002 -s 192.168.0.0/16 -j DROP

=== Router Port Forwarding ===
Forward ports 7001-7002 to WRF storage node IP
Enable UPnP ONLY for WRF VLAN (not recommended for security)
EOF
    
    print_success "Firewall configuration guide created"
}

# Network test function
test_network() {
    print_info "Testing network connectivity..."
    
    # Test internal connectivity
    if curl -s -f "http://localhost:7001/health" > /dev/null 2>&1; then
        print_success "Internal health check passed"
    else
        print_warning "Internal health check failed (container may not be running yet)"
    fi
    
    # Test external DNS
    if ping -c 1 8.8.8.8 > /dev/null 2>&1; then
        print_success "External connectivity test passed"
    else
        print_warning "External connectivity test failed"
    fi
}

# Main setup function
main() {
    print_info "Starting WRF Storage Node setup for Unraid..."
    print_info "================================================="
    
    # Pre-flight checks
    check_unraid
    check_plugins
    
    # Setup storage and configuration
    setup_storage_drive
    setup_config_directory
    
    # Generate configuration files
    generate_env_file
    setup_docker_compose
    create_monitoring_scripts
    create_firewall_config
    
    print_success "Setup completed successfully!"
    print_info ""
    print_info "Next Steps:"
    print_info "1. Edit $WRF_CONFIG_DIR/.env and set your WRF wallet address"
    print_info "2. Review and configure network isolation (see firewall-rules.txt)"
    print_info "3. Start the container: cd $WRF_CONFIG_DIR && docker-compose up -d"
    print_info "4. Monitor logs: docker-compose logs -f"
    print_info "5. Set up monitoring scripts in User Scripts plugin"
    print_info ""
    print_warning "SECURITY WARNING: Do not start the container until network isolation is configured!"
    print_info ""
    print_info "Support: Check the documentation in /docs/unraid-wrf-storage-deployment.md"
}

# Run main function
main "$@"